/**
 * MOBILE-FIRST v5 — PHASE 1: portrait-stage fallback variant generator
 *
 * The <PortraitStage /> ships a FALLBACK portrait (framed 7:9 over the shape)
 * until the transparent cutout (TODO(asset)) is supplied. This script produces
 * that framed portrait's 7:9 ladder in AVIF + WebP + JPEG into public/stage/.
 *
 * Source: src/assets/images/mdshawonmolla.jpg — the highest-resolution master in
 * the project (1024x1024, opaque). It is a better source than the 800x800 file
 * the v4 hero ladder uses, so the stage gets the most honest pixels available.
 *
 * Honest width ladder
 * -------------------
 * A framed 7:9 crop of a 1024x1024 square caps at floor(min(1024, 1024*7/9)) =
 * 796px wide. The brief asks for ~480/720/960/1200. 960 and 1200 would require
 * upscaling, which invents facial detail, so this script refuses to emit them and
 * records them as missing. Dropping in the >=1200px transparent cutout and
 * re-running (or switching the stage to the cutout path) yields the full ladder
 * with no component change.
 *
 * Usage:  npm run stage:build
 */

import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';

const SOURCE = path.resolve('src/assets/images/mdshawonmolla.jpg');
const OUT_DIR = path.resolve('public/stage');
const MANIFEST = path.resolve('src/data/stagePortraitManifest.ts');

// 7:9 passport ratio — matches the framed fallback and the phone stage aspect.
const RATIO_W = 7;
const RATIO_H = 9;

// Target ladder from the brief. Anything above the honest 7:9 ceiling is skipped.
const LADDER = [480, 720, 960, 1200];

// Slightly higher quality than the v4 hero ladder (brief budget ~150 KB for the
// stage): the face is the focal point and large on screen.
const QUALITY = { avif: 56, webp: 82, jpg: 86 };
const BUDGET_KB = 150;

const bytes = (n) => (n / 1024).toFixed(1) + ' KB';

async function main() {
  if (!fs.existsSync(SOURCE)) {
    console.error(`Missing source: ${SOURCE}`);
    process.exit(1);
  }

  const meta = await sharp(SOURCE).metadata();
  const srcW = meta.width;
  const srcH = meta.height;
  const maxHonestW = Math.floor(Math.min(srcW, (srcH * RATIO_W) / RATIO_H));

  console.log(`source : ${srcW}x${srcH} (${(srcW / srcH).toFixed(3)})`);
  console.log(`7:9    : widest honest framed derivative = ${maxHonestW}px wide`);
  if (maxHonestW < 1200) {
    console.log(
      `\n  !! TODO(asset): the framed fallback is capped at ${maxHonestW}px by the\n` +
        `     7:9 crop of the ${srcW}px square master. 960/1200 srcset entries need the\n` +
        `     >=1200px transparent cutout (see Phase 0 asset spec) and are NOT emitted\n` +
        `     here because upscaling would invent facial detail.\n`,
    );
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const widths = LADDER.filter((w) => w <= maxHonestW);
  const skipped = LADDER.filter((w) => w > maxHonestW);
  const produced = [];

  for (const w of widths) {
    const height = Math.round((w * RATIO_H) / RATIO_W);
    // Crop square -> 7:9, top-biased so hair is never shaved; micro-contrast so
    // the face reads against the dark stage.
    const pipeline = sharp(SOURCE)
      .resize({ width: w, height, fit: 'cover', position: 'top' })
      .modulate({ saturation: 1.03 })
      .linear(1.05, -5)
      .sharpen({ sigma: 0.7 });

    const entry = { width: w, height };
    for (const fmt of ['avif', 'webp', 'jpg']) {
      const file = `${w}.${fmt}`;
      const out = path.join(OUT_DIR, file);
      let img = pipeline.clone();
      if (fmt === 'avif') img = img.avif({ quality: QUALITY.avif, effort: 6 });
      else if (fmt === 'webp') img = img.webp({ quality: QUALITY.webp, effort: 5 });
      else img = img.jpeg({ quality: QUALITY.jpg, mozjpeg: true, chromaSubsampling: '4:4:4' });
      await img.toFile(out);
      entry[fmt] = { file: `/stage/${file}`, bytes: fs.statSync(out).size };
    }
    produced.push(entry);
    console.log(
      `  ${String(w).padStart(4)}px  avif ${bytes(entry.avif.bytes).padStart(9)}  ` +
        `webp ${bytes(entry.webp.bytes).padStart(9)}  jpg ${bytes(entry.jpg.bytes).padStart(9)}`,
    );
  }

  // ---- budget check (brief: ~150 KB at the largest variant) ----
  const largest = produced.at(-1);
  console.log(`\nbudget : largest variant ${largest.width}px -> avif ${bytes(largest.avif.bytes)}, webp ${bytes(largest.webp.bytes)}`);
  const overBudget = produced.filter((p) => p.avif.bytes > BUDGET_KB * 1024);
  if (overBudget.length) {
    console.log(`  !! over the ${BUDGET_KB} KB avif budget: ${overBudget.map((p) => p.width + 'px').join(', ')}`);
  } else {
    console.log(`  OK - every avif variant is under the ${BUDGET_KB} KB budget`);
  }

  // ---- manifest consumed by <PortraitStage /> (fallback portrait) ----
  const ts = `/**
 * AUTO-GENERATED by scripts/build-stage-portrait.mjs — do not edit by hand.
 * Regenerate with: npm run stage:build
 *
 * FRAMED FALLBACK ladder (7:9). Used by <PortraitStage /> until the transparent
 * cutout (TODO(asset)) is supplied; the cutout path will ship its own ladder.
 */

export const STAGE_PORTRAIT_WIDTHS = [${produced.map((p) => p.width).join(', ')}] as const;

export const STAGE_PORTRAIT_SRCSET = {
  avif: '${produced.map((p) => `/stage/${p.width}.avif ${p.width}w`).join(', ')}',
  webp: '${produced.map((p) => `/stage/${p.width}.webp ${p.width}w`).join(', ')}',
  jpg:  '${produced.map((p) => `/stage/${p.width}.jpg ${p.width}w`).join(', ')}',
} as const;

export const STAGE_PORTRAIT_INTRINSIC = { width: ${largest.width}, height: ${largest.height} } as const;

export const STAGE_PORTRAIT_FALLBACK_SRC = '/stage/${Math.min(480, largest.width)}.jpg';

export const STAGE_PORTRAIT_MISSING_WIDTHS = [${skipped.join(', ')}] as const;
`;
  fs.writeFileSync(MANIFEST, ts);
  console.log(`\nwrote ${path.relative(process.cwd(), MANIFEST)}`);
  if (skipped.length) console.log(`TODO(asset): missing widths ${skipped.join(', ')} (need the >=1200px cutout)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});